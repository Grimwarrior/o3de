import sys, io, os

PATH = os.environ["HOME"] + "/mnt/o3de/Gems/Atom/Tools/MaterialCanvas/Code/Source/MaterialCanvasApplication.cpp"

with io.open(PATH, "r", encoding="utf-8", newline="") as f:
    data = f.read()
eol = "\r\n" if "\r\n" in data else "\n"
def L(lines): return eol.join(lines)

old = L([
'    void MaterialCanvasApplication::ApplyPreviewMaterialPipelineSettings()',
'    {',
'        // If the preview-only material pipeline is enabled, copy a settings registry file stub into the user settings folder. It replaces',
'        // /O3DE/Atom/RPI/MaterialPipelineFiles with a single trimmed pipeline, which MaterialTypeBuilder reads when it expands an abstract',
'        // material type into shaders. The default list names both MainPipeline and LowEndPipeline, and for a Standard lighting model those',
'        // two produce 21 shaders between them. The preview pipeline produces four and drops LowEndPipeline entirely.',
'        //',
'        // This is an Asset Processor side setting, so it applies to every material type in the project while it is enabled, not just the',
'        // graph being edited, and both this application and the Asset Processor have to be restarted for a change to take effect. Turning',
'        // it back off restores the stock pipelines and the assets they generate.',
'        if (auto fileIO = AZ::IO::FileIOBase::GetInstance())',
'        {',
'            const AZ::IO::FixedMaxPath materialCanvasGemPath = AZ::Utils::GetGemPath("MaterialCanvas");',
'            const auto settingsPathStub(',
'                materialCanvasGemPath / AZ::SettingsRegistryConstants::RegistryFolder / "user_preview_material_pipeline.setregstub");',
'',
'            const AZ::IO::FixedMaxPath projectPath = AZ::Utils::GetProjectPath();',
'            const auto settingsPath(',
'                projectPath / AZ::SettingsRegistryConstants::DevUserRegistryFolder / "user_preview_material_pipeline.setreg");',
'',
'            if (AtomToolsFramework::GetSettingsValue<bool>("/O3DE/Atom/MaterialCanvas/EnablePreviewOnlyMaterialPipeline", false))',
'            {',
'                fileIO->Copy(settingsPathStub.c_str(), settingsPath.c_str());',
'            }',
'            else',
'            {',
'                fileIO->Remove(settingsPath.c_str());',
'            }',
'        }',
'    }',
])

new = L([
'    void MaterialCanvasApplication::ApplyPreviewMaterialPipelineSettings()',
'    {',
'        // The preview-only material pipeline is no longer selected by swapping the project\'s pipeline list. Material types generated by',
'        // Material Canvas declare the preview pipeline themselves, in their build settings, so the choice applies to the graphs being',
'        // edited instead of to every material type in the project, and it takes effect on the next compile rather than the next restart.',
'        //',
'        // MaterialCanvasEditorSystemComponent was changed to match when that landed. This copy was not, and the disagreement between the',
'        // two was doing real damage, because the standalone tool created the file on startup and the Editor deleted it on startup:',
'        //',
'        //   - Every switch between the two applications replaced /O3DE/Atom/RPI/MaterialPipelineFiles for the whole project and put it',
'        //     back. Every material type in the project changed its job set, so the Asset Processor rebuilt all of them, twice per round',
'        //     trip. That is the "opening the Editor reprocesses every material" symptom, in both directions.',
'        //   - The production output asks for MainPipeline by name. While the file was present, the list that name is resolved against',
'        //     held nothing but the preview pipeline, so the production material type was built through the preview pipeline instead.',
'        //   - Worst of all, one source\'s products were being deleted for the pipeline it had just left while being inserted for the one',
'        //     it had just joined. The names collided, InsertProduct hit a uniqueness constraint, and the Asset Processor answered by',
'        //     quitting: "Failed to execute the AssetProcessor::InsertProduct statement", followed immediately by "App quit requested".',
'        //',
'        // All that remains here is removing the settings registry file older builds copied into the project. Left behind it would still',
'        // replace /O3DE/Atom/RPI/MaterialPipelineFiles for everything, which is exactly the behaviour being retired, and it would do so',
'        // silently because nothing writes it any more.',
'        if (auto fileIO = AZ::IO::FileIOBase::GetInstance())',
'        {',
'            const AZ::IO::FixedMaxPath projectPath = AZ::Utils::GetProjectPath();',
'            const auto settingsPath(',
'                projectPath / AZ::SettingsRegistryConstants::DevUserRegistryFolder / "user_preview_material_pipeline.setreg");',
'',
'            if (fileIO->Exists(settingsPath.c_str()))',
'            {',
'                fileIO->Remove(settingsPath.c_str());',
'            }',
'        }',
'    }',
])

n = data.count(old)
if n != 1:
    print("FAIL: found %d occurrences (expected 1)" % n); sys.exit(1)
data = data.replace(old, new, 1)
with io.open(PATH, "w", encoding="utf-8", newline="") as f:
    f.write(data)
print("applied (eol=%s)" % repr(eol))
